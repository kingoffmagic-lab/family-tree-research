#!/usr/bin/env python3
"""Generate compact country guides; JSON is authoritative."""
import argparse
from common import ROOT,read_json
MARKER='<!-- Generated by scripts/render_catalogue.py; edit JSON. -->\n\n'
def link(url,label=None):return '['+(label or url).replace('|','\\|')+']('+url+')'
def generated():
 db=read_json(ROOT/'regional-archives/data/archives.json');js=read_json(ROOT/'regional-archives/data/jurisdictions.json');cv=read_json(ROOT/'regional-archives/data/coverage.json');ss=read_json(ROOT/'resources/sources.json')
 files={};archives=db['archives'];regions=js['regions'];coverage={c['region_id']:c for c in cv['regions']}
 for c in db['countries']:
  country=c['id'];rr=[r for r in regions if r['country']==country];aa=[a for a in archives if a['country']==country]
  text='# '+c['name']+'\n\n[Directory](../../README.md) · '+link(c['directory_url'],'Official directory')+'\n\n'
  text+='## Regions and service areas\n\n'
  for region in rr:
   text+='- **'+region['name']+'**: '+(', '.join(link('#'+a['id'],a['official_name']) for a in aa if region['id'] in a['region_ids']) or 'Not mapped; consult the official directory.')+'\n'
  text+='\n## Institutions\n\n'
  for a in aa:
   text+='<a id="'+a['id']+'"></a>\n\n### '+a['official_name']+'\n\n'
   text+='`'+a['kind']+'` · '+link(a['website_url'] or a['directory_url'],'Website / directory')+'\n\n'+a['description']+'\n\n'
   urls=list(dict.fromkeys(a['catalogue_urls']+a['inventory_urls']+a['reading_room_urls']+a['finding_aid_urls']))
   if urls:text+='Links: '+' · '.join(link(u) for u in urls)+'\n\n'
   if a['documented_holdings']:text+='Holdings: '+'; '.join(a['documented_holdings'])+'\n\n'
   if a['documented_date_range']:text+='Dates: '+a['documented_date_range']+'\n\n'
   if a['record_languages']:text+='Languages: '+', '.join(a['record_languages'])+'\n\n'
   if a['former_names']:text+='Former names: '+'; '.join(a['former_names'])+'\n\n'
   text+='Source: '+' · '.join(link(u) for u in a['verification']['source_urls'])+' · '+a['verification']['checked_at']+' · '+a['verification']['method']+'\n\n'
   if any(a['gaps'] != other['gaps'] for other in aa):
    shared=max((other['gaps'] for other in aa),key=lambda g:sum(o['gaps']==g for o in aa))
    if a['gaps'] != shared:text+='Gaps: '+'; '.join(a['gaps'])+'\n\n'
  text+='## Coverage\n\nPartial. Institution and branch lists are not fully reconciled. Unknown holdings, dates, languages and viewing conditions remain unknown. '+link('../../historical/finding-a-volost.md','Historical place lookup')+'.\n'
  files['regional-archives/countries/'+country+'/README.md']=MARKER+text
 text='# Regional archives\n\n'+str(len(archives))+' institutions, authorities and service points; '+str(len(regions))+' browsing units. Checked '+db['as_of']+'.\n\n'
 text+='**Coverage is partial.** A listing does not establish surviving records or open scans. Resolve event-date jurisdiction and record creator before choosing a keeper. Authorities and service offices are not automatically holding repositories.\n\n'
 text+='\n'.join('- '+link('countries/'+c['id']+'/README.md',c['name']) for c in db['countries'])+'\n\n'
 text+='## Use\n\nSearch locality variants, date and record type with `scripts/search_catalogue.py`. Check fonds and inventories before names. Users handle login, payment and requests; agents stop restricted routes.\n\n'
 text+='[Historical locality lookup](historical/finding-a-volost.md) · [Empire](historical/russian-empire.md) · [USSR](historical/soviet-union.md) · [External custodians](external-custodians/README.md) · [Coverage](COVERAGE.md).\n\n'
 text+='Data: archives.json stores institution facts; jurisdictions.json stores browsing units and historical routes; coverage.json stores unresolved work. Shared defaults and verification references are expanded by scripts/common.py. Generated country guides are the only Markdown copy of institution descriptions.\n'
 files['regional-archives/README.md']=MARKER+text
 text='# Coverage\n\nPartial directory as of '+cv['as_of']+'. No region is yet marked fully reconciled.\n\n| Country | Institutions | Browsing units |\n|---|---:|---:|\n'
 for c in db['countries']:text+='| '+link('countries/'+c['id']+'/README.md',c['name'])+' | '+str(sum(a['country']==c['id'] for a in archives))+' | '+str(sum(r['country']==c['id'] for r in regions))+' |\n'
 text+='\n'+'\n'.join('- '+v for v in js['territorial_notes'])+'\n\nCompletion requires a dated official list, branch reconciliation, transfer review and a written explanation. A failed connection never removes an institution.\n'
 files['regional-archives/COVERAGE.md']=MARKER+text
 text='# Other sources\n\n'+link('../regional-archives/README.md','Regional archives')+' · '+link('../vendor/ex-ussr-kinship-research/references/seed-sources.md','Upstream specialist sources')+'\n\nGeneral links only. Descriptions identify research routes, not tested item-level availability. Verify coverage, provenance and current restrictions for the chosen collection.\n\n'
 for category in sorted({s['category'] for s in ss['sources']}):
  text+='## '+category.replace('-',' ').title()+'\n\n'
  for s in ss['sources']:
   if s['category']==category:text+='### '+link(s['url'],s['title'])+'\n\n'+s['description']+'\n\n'
 files['resources/README.md']=MARKER+text
 return files

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();stale=[]
 for name,text in generated().items():
  path=ROOT/name
  if a.check:
   if not path.exists() or path.read_text()!=text:stale.append(name)
  else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
 if stale:print('Stale: '+', '.join(stale));return 1
 print(('Checked' if a.check else 'Generated')+' compact catalogue guides');return 0
if __name__=='__main__':raise SystemExit(main())
